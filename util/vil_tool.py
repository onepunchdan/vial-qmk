#!/usr/bin/env python3
"""Convert Vial .vil layouts to a QMK keymap header, and check vial.json against qmk info."""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Vial GUI (old QMK) names -> current QMK names. Extend only as compile errors demand.
_EXPLICIT = {
    "KC_LSHIFT": "KC_LSFT", "KC_RSHIFT": "KC_RSFT",
    "KC_LCTRL": "KC_LCTL", "KC_RCTRL": "KC_RCTL",
    "KC_PSCREEN": "KC_PSCR", "KC_SCROLLLOCK": "KC_SCRL",
    "KC_APPLICATION": "KC_APP",
}


def _load_ensure_aliases():
    """Object-like `#define OLD NEW` pairs from vial_ensure_keycode.h (its aliases are #undef'd, so keymaps can't see them)."""
    path = REPO / "quantum" / "vial_ensure_keycode.h"
    out = {}
    if path.exists():
        for line in path.read_text().splitlines():
            m = re.match(r"#define\s+([A-Za-z_]\w*)\s+([A-Za-z_]\w*)\s*(?://.*)?$", line)
            if m:
                out[m.group(1)] = m.group(2)
    return out


LEGACY = {**_load_ensure_aliases(), **_EXPLICIT}


def convert_keycode(name, renames):
    if name == -1:
        return "KC_NO"
    name = str(name)
    if re.fullmatch(r"0[xX][0-9a-fA-F]+", name):
        return name
    m = re.fullmatch(r"LT(\d+)\((.*)\)", name)
    if m:
        return "LT(%s, %s)" % (m.group(1), convert_keycode(m.group(2), renames))

    def tok(m):
        t = m.group(0)
        if t in renames:
            return renames[t]
        u = re.fullmatch(r"USER(\d+)", t)
        if u:
            return "QK_KB_%d" % int(u.group(1))
        return LEGACY.get(t, t)

    return re.sub(r"[A-Za-z_]\w*", tok, name)


def _kc(lst, renames):
    return ", ".join(convert_keycode(k, renames) for k in lst)


def _trim(entries, empty_key):
    """Entries 0..last non-empty, keeping index positions."""
    last = -1
    for i, e in enumerate(entries):
        if any(k != "KC_NO" for k in e[:empty_key]):
            last = i
    return entries[:last + 1]


def vil_to_header(vil, renames, source="<vil>", layout_macro=None, keyboard=None):
    out = ["// Generated by util/vil_tool.py from %s%s. Do not edit." % (source, " for " + keyboard if keyboard else ""),
           "#pragma once", ""]
    if layout_macro:
        out += ["#define VIL_LAYOUT_MACRO %s" % layout_macro, ""]

    def macro(name, lines):
        out.append("#define %s \\" % name)
        out.append(" \\\n".join(["{"] + lines + ["}"]))
        out.append("")

    layers = []
    for n, layer in enumerate(vil["layout"]):
        rows = ["{%s}" % _kc(r, renames) for r in layer]
        layers.append("    /* layer %d */ { %s }," % (n, ", ".join(rows)))
    macro("VIL_KEYMAPS", layers)

    if "encoder_layout" in vil:
        enc = []
        for n, layer in enumerate(vil["encoder_layout"]):
            es = ["ENCODER_CCW_CW(%s)" % _kc(e, renames) for e in layer]
            enc.append("    /* layer %d */ { %s }," % (n, ", ".join(es)))
        macro("VIL_ENCODER_MAP", enc)

    td = [[convert_keycode(k, renames) for k in e[:4]] + [e[4]]
          for e in vil.get("tap_dance", [])]
    td = _trim(td, 4)
    td = [e if any(k != "KC_NO" for k in e[:4]) else e[:4] + [200] for e in td]
    macro("VIL_TAP_DANCE", ["    {%s}," % ", ".join(map(str, e)) for e in td])
    out += ["#define VIL_TAP_DANCE_COUNT %d" % len(td), ""]

    cb = [[convert_keycode(k, renames) for k in e] for e in vil.get("combo", [])]
    cb = _trim(cb, 5)
    macro("VIL_COMBOS", ["    {{%s}, %s}," % (", ".join(e[:4]), e[4]) for e in cb])
    out += ["#define VIL_COMBO_COUNT %d" % len(cb), ""]
    return "\n".join(out)


def vialjson_positions(vialjson):
    pos = set()
    for row in vialjson["layouts"]["keymap"]:
        for item in row:
            if not isinstance(item, str):
                continue
            lines = item.split("\n")
            if len(lines) > 9 and lines[9] == "e":
                continue
            m = re.fullmatch(r"(\d+),(\d+)", lines[0])
            if m:
                pos.add((int(m.group(1)), int(m.group(2))))
    return pos


def qmk_positions(keyboard):
    res = subprocess.run(["qmk", "info", "-kb", keyboard, "-f", "json"], cwd=REPO,
                         capture_output=True, text=True, check=True)
    layouts = json.loads(res.stdout)["layouts"]
    return {tuple(k["matrix"]) for lay in layouts.values() for k in lay["layout"]}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keymap")
    k.add_argument("vil")
    k.add_argument("keyboard_name", help="informational only; written into the header comment")
    k.add_argument("out")
    k.add_argument("--rename", action="append", default=[], metavar="OLD=NEW")
    k.add_argument("--layout-macro")
    c = sub.add_parser("check-vialjson")
    c.add_argument("vialjson")
    c.add_argument("keyboard_name")
    a = p.parse_args(argv)

    if a.cmd == "keymap":
        renames = dict(r.split("=", 1) for r in a.rename)
        with open(a.vil) as f:
            vil = json.load(f)
        Path(a.out).write_text(vil_to_header(vil, renames, Path(a.vil).name, a.layout_macro, a.keyboard_name))
        return 0

    with open(a.vialjson) as f:
        have = vialjson_positions(json.load(f))
    want = qmk_positions(a.keyboard_name)
    if have == want:
        print("OK: %d positions match" % len(have))
        return 0
    print("only in vial.json:", sorted(have - want))
    print("only in qmk info:", sorted(want - have))
    return 1


if __name__ == "__main__":
    sys.exit(main())
